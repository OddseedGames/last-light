async () => {
  const canvas = document.querySelector('canvas');
  const state = () => Object.fromEntries(Object.entries(document.querySelector('#game-status').dataset).map(([key, value]) => [key, Number(value)]));
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const key = (code, down) => canvas.dispatchEvent(new KeyboardEvent(down ? 'keydown' : 'keyup', {code, bubbles: true, cancelable: true}));
  const press = async code => { key(code, true); await wait(70); key(code, false); await wait(70); };
  const aim = (x, y) => {
    const box = canvas.getBoundingClientRect();
    canvas.dispatchEvent(new MouseEvent('mousemove', {clientX:box.x + x / 1280 * box.width, clientY:box.y + y / 880 * box.height, bubbles:true}));
  };
  canvas.focus();
  check(document.querySelector('#loading').hidden, 'Loading overlay remains visible');
  check(document.querySelector('#load-error').hidden, 'Loading failed');
  if (state().phase === 0) await press('Enter');
  if (state().phase === 2) await press('Enter');
  check(state().phase === 1, 'Game did not start');
  const start = state();
  key('KeyD', true); key('KeyW', true);
  await wait(400);
  key('KeyD', false); key('KeyW', false);
  await wait(80);
  const moved = state();
  check(moved.x > start.x + 30 && moved.y < start.y - 30, 'WASD movement failed');
  aim(moved.x + 28 + 180, moved.y + 110);
  await wait(120);
  check(Math.abs(state().angle) < 0.05, 'Mouse aim failed');
  key('KeyQ', true); await wait(350); key('KeyQ', false);
  await wait(80);
  check(state().angle < -0.7, 'Keyboard light rotation failed');
  const keyboardAngle = state().angle;
  await wait(160);
  check(Math.abs(state().angle - keyboardAngle) < 0.01, 'Stationary mouse overrode keyboard rotation');
  aim(moved.x + 28 + 185, moved.y + 110 + 2);
  await wait(120);
  check(Math.abs(state().angle) < 0.05, 'Mouse did not regain aim');
  key('Space', true);
  await wait(2900);
  key('Space', false);
  await wait(80);
  const empty = state();
  check(empty.fired === 6 && empty.ammo === 0 && empty.reload > 0, 'Six-shot magazine or automatic reload failed');
  await wait(1800);
  check(state().ammo === 6 && state().reload === 0, 'Automatic reload did not complete');
  await press('Space');
  await press('KeyR');
  check(state().reload > 0 && state().ammo === 5, 'Manual reload failed');
  await press('KeyP');
  const paused = state();
  check(paused.phase === 2, 'Pause failed');
  await wait(400);
  check(JSON.stringify(state()) === JSON.stringify(paused), 'Simulation continued while paused');
  await press('Enter');
  check(state().phase === 1, 'Resume failed');
  window.dispatchEvent(new Event('blur'));
  await wait(100);
  check(state().phase === 2, 'Blur did not pause the game');
  await press('KeyN');
  const reset = state();
  check(reset.phase === 1 && reset.health === 3 && reset.ammo === 6 && reset.kills === 0 && reset.elapsed < 0.5, 'Round reset failed');
  await press('KeyP');
  return {passed: ['offline standalone boot', 'WASD', 'mouse aim', 'keyboard rotation', 'six-shot magazine', 'automatic reload', 'manual reload', 'pause freezes state', 'resume', 'blur pause', 'restart'], state:state(), externalRequests:performance.getEntriesByType('resource').filter(entry => /^https?:/.test(entry.name)).map(entry=>entry.name)};
}
